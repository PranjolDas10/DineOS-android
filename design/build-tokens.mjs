// Generates app/src/main/java/dev/dineos/app/ui/theme/Tokens.kt from design/tokens.json, the
// same file the web dashboard builds its CSS variables from (contrast is checked there).
// CI reruns this and fails if the committed Kotlin drifted. Usage: node design/build-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("design/tokens.json", root), "utf8"));

const primitive = (ref) => {
  const value = ref.split(".").reduce((node, key) => node?.[key], tokens.primitive);
  if (typeof value !== "string") throw new Error(`Unknown primitive "${ref}"`);
  return value;
};
const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const names = Object.keys(tokens.semantic.light);
const theme = (key) =>
  names.map((n) => `    ${camel(n)} = Color(0xFF${primitive(tokens.semantic[key][n]).slice(1).toUpperCase()}),`).join("\n");

writeFileSync(
  new URL("app/src/main/java/dev/dineos/app/ui/theme/Tokens.kt", root),
  `// Generated by design/build-tokens.mjs from design/tokens.json. Do not edit.
package dev.dineos.app.ui.theme

import androidx.compose.ui.graphics.Color

data class Tokens(
${names.map((n) => `    val ${camel(n)}: Color,`).join("\n")}
)

val LightTokens = Tokens(
${theme("light")}
)

val DarkTokens = Tokens(
${theme("dark")}
)
`,
);
