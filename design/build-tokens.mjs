// Generates ui/theme/Tokens.kt and res/values*/colors.xml from design/tokens.json, the same file
// the web dashboard builds its CSS variables from (contrast is checked there).
// CI reruns this and fails if a committed copy drifted. Usage: node design/build-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("design/tokens.json", root), "utf8"));

const primitive = (ref) => {
  const value = ref.split(".").reduce((node, key) => node?.[key], tokens.primitive);
  if (typeof value !== "string") throw new Error(`Unknown primitive "${ref}"`);
  return value;
};
const hex = (ref) => `#${primitive(ref).slice(1).toUpperCase()}`;
const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const names = Object.keys(tokens.semantic.light);
const theme = (key) =>
  names.map((n) => `    ${camel(n)} = Color(0xFF${primitive(tokens.semantic[key][n]).slice(1).toUpperCase()}),`).join("\n");

writeFileSync(
  new URL("app/src/main/java/dev/dineos/app/ui/theme/Tokens.kt", root),
  `// Generated by design/build-tokens.mjs from design/tokens.json. Do not edit.
package dev.dineos.app.ui.theme

import androidx.compose.ui.graphics.Color

data class Tokens(
${names.map((n) => `    val ${camel(n)}: Color,`).join("\n")}
)

val LightTokens = Tokens(
${theme("light")}
)

val DarkTokens = Tokens(
${theme("dark")}
)
`,
);

// The XML resource layer (the launch window, the launcher icon) is drawn before any Kotlin runs,
// so it can't read Tokens.kt. The two colors it needs are generated here too.
const colors = (key, extra = "") => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/build-tokens.mjs from design/tokens.json. Do not edit. -->
<resources>
    <!-- What the window paints before Compose draws. Token: bg. -->
    <color name="token_bg">${hex(tokens.semantic[key].bg)}</color>${extra}
</resources>
`;

writeFileSync(
  new URL("app/src/main/res/values/colors.xml", root),
  colors(
    "light",
    `
    <!-- The launcher icon's background: the light theme's primary, the same in both themes
         because a home screen icon doesn't follow the app's dark mode. -->
    <color name="ic_launcher_background">${hex(tokens.semantic.light.primary)}</color>`,
  ),
);
writeFileSync(new URL("app/src/main/res/values-night/colors.xml", root), colors("dark"));
